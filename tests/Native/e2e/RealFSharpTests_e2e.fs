// ─────────────────────────────────────────────────────────────────────────────
// 1. Pipeline Helper: Wire up to the CLI
// ─────────────────────────────────────────────────────────────────────────────
module PipelineHelper =
    
    /// Compiles an F# project directory to WasmGC by shelling out to Fable CLI
    let compileToWasm (projectDir: string) (outDir: string) =
        let psi = ProcessStartInfo("dotnet")
        
        // Match the Fable CLI arguments from your run.sh files
        // Note: adjust the path to Fable.Cli based on your test runner's working directory
        // let fableCliPath = Path.GetFullPath("../../vendor/Fable/src/Fable.Cli") 
        let fsharpWasmCliPath = Path.Combine(__SOURCE_DIRECTORY__, "../../../tools/FSharp.Wasm.Cli")
        psi.Arguments <- $"run --project \"{fsharpWasmCliPath}\" -- \"{projectDir}\" --outDir \"{outDir}\" --noCache"
        
        psi.RedirectStandardOutput <- true
        psi.RedirectStandardError <- true
        psi.UseShellExecute <- false
        
        use p = Process.Start(psi)
        p.WaitForExit()
        
        let stdout = p.StandardOutput.ReadToEnd()
        let stderr = p.StandardError.ReadToEnd()
        
        if p.ExitCode <> 0 then
            failwithf "CLI Compilation failed (Exit %d):\nSTDERR:\n%s\nSTDOUT:\n%s" p.ExitCode stderr stdout
            
        // Discover the generated .wasm and .wat files
        let projName = Path.GetFileName(projectDir) // e.g., "App" from "App.fsproj"
        let wasmPath = Path.Combine(outDir, projName + ".wasm")
        let watPath = Path.Combine(outDir, projName + ".wat")
        
        if not (File.Exists(wasmPath)) then
            failwithf "Expected WASM output not found at: %s" wasmPath
            
        (wasmPath, watPath)

    /// Runs a compiled WASM module via Wasmtime to verify execution correctness
    let runWasmtime (wasmPath: string) =
        let psi = ProcessStartInfo("wasmtime")
        psi.Arguments <- $"run \"{wasmPath}\""
        psi.RedirectStandardOutput <- true
        psi.RedirectStandardError <- true
        psi.UseShellExecute <- false
        
        use p = Process.Start(psi)
        p.WaitForExit()
        
        let stdout = p.StandardOutput.ReadToEnd()
        let stderr = p.StandardError.ReadToEnd()
        
        if p.ExitCode <> 0 then
            failwithf "Wasmtime execution failed:\n%s" stderr
            
        stdout

